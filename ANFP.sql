-- CREACION DE TABLAS


-- ====================================================
-- 1. TABLA REGION
-- ====================================================

CREATE TABLE region (
    id_region     NUMBER(2)    NOT NULL,
    nombre_region VARCHAR2(30) NOT NULL
);

    ALTER TABLE region ADD CONSTRAINT region_pk PRIMARY KEY (id_region);


-- ====================================================
-- 2. TABLA NACIONALIDAD
-- ====================================================

CREATE TABLE nacionalidad (
    id_nacion NUMBER(3)
    GENERATED BY DEFAULT AS IDENTITY (START WITH 210 INCREMENT BY 2),
    nom_nacion VARCHAR2(25) NOT NULL
);

    ALTER TABLE nacionalidad ADD CONSTRAINT nacionalidad_pk PRIMARY KEY (id_nacion);


-- ====================================================
-- 3. TABLA ASOCIACION
-- ====================================================

CREATE TABLE asociacion (
    cod_asociacion NUMBER(2)    NOT NULL,
    nombre         VARCHAR2(50) NOT NULL,
    fecha_creacion DATE         NOT NULL,
    tipo           VARCHAR2(11) NOT NULL
);

    ALTER TABLE asociacion ADD CONSTRAINT asociacion_pk PRIMARY KEY (cod_asociacion);
    ALTER TABLE asociacion ADD CONSTRAINT asociacion_fecha_ck CHECK (fecha_creacion >= DATE '1980-12-31');


-- ====================================================
-- 4. TABLA CLUB_FUTBOL
-- ====================================================

CREATE TABLE club_futbol (
    id_club     NUMBER(3)    NOT NULL,
    nombre_club VARCHAR2(50) NOT NULL,
    patrimonio  NUMBER(10)   NOT NULL,
    calle       VARCHAR2(30) NOT NULL,
    numero      VARCHAR2(5)  NOT NULL,
    tipo_club   VARCHAR2(11) NOT NULL
);

    ALTER TABLE club_futbol ADD CONSTRAINT club_futbol_pk PRIMARY KEY (id_club);
    ALTER TABLE club_futbol ADD CONSTRAINT club_futbol_nombre_un UNIQUE (nombre_club);


-- ====================================================
-- 5. TABLA ESCUELA_FUTBOL
-- ====================================================

CREATE TABLE escuela_futbol (
    id_escuela      NUMBER(4)    NOT NULL,
    nombre          VARCHAR2(50) NOT NULL,
    capacidad       NUMBER(3)    NOT NULL,
    fecha_fundacion DATE         NOT NULL
);

    ALTER TABLE escuela_futbol ADD CONSTRAINT escuela_futbol_pk PRIMARY KEY (id_escuela);


-- ====================================================
-- 6. TABLA IDIOMA
-- ====================================================

CREATE TABLE idioma (
    id_idioma CHAR(3)      NOT NULL,
    idioma    VARCHAR2(20) NOT NULL
);

    ALTER TABLE idioma ADD CONSTRAINT idioma_pk PRIMARY KEY (id_idioma);


-- ====================================================
-- 7. TABLA COMUNA
-- ====================================================

CREATE TABLE comuna (
    id_comuna        NUMBER(3)    NOT NULL,
    nombre_comuna    VARCHAR2(30) NOT NULL,
    region_id_region NUMBER(2)    NOT NULL
);

    ALTER TABLE comuna ADD CONSTRAINT comuna_pk PRIMARY KEY (id_comuna);
    ALTER TABLE comuna ADD CONSTRAINT comuna_region_fk FOREIGN KEY (region_id_region) REFERENCES region(id_region);


-- ====================================================
-- 8. TABLA TRABAJADOR
-- ====================================================

CREATE TABLE trabajador (
    nro_inscripcion        NUMBER(9)    NOT NULL,
    rut                    NUMBER(8)    NOT NULL,
    dv                     CHAR(1)      NOT NULL,
    pnombre                VARCHAR2(20) NOT NULL,
    snombre                VARCHAR2(20) NOT NULL,
    apaterno               VARCHAR2(20) NOT NULL,
    amaterno               VARCHAR2(20) NOT NULL,
    sueldo_base            NUMBER(10)   NOT NULL,
    fecha_nac              DATE         NOT NULL,
    genero                 VARCHAR2(9)  NOT NULL,
    estado_civil           VARCHAR2(10) NOT NULL,
    telefono               VARCHAR2(12) NOT NULL,
    calle                  VARCHAR2(20) NOT NULL,
    num_calle              VARCHAR2(5)  NOT NULL,
    comuna_id_comuna       NUMBER(3)    NOT NULL,
    nacionalidad_id_nacion NUMBER(3)    NOT NULL
);

    ALTER TABLE trabajador ADD CONSTRAINT trabajador_pk PRIMARY KEY (nro_inscripcion);
    ALTER TABLE trabajador ADD CONSTRAINT trabajador_rut_un UNIQUE (rut);
    ALTER TABLE trabajador ADD CONSTRAINT trabajador_comuna_fk FOREIGN KEY (comuna_id_comuna) REFERENCES comuna(id_comuna);
    ALTER TABLE trabajador ADD CONSTRAINT trabajador_nacionalidad_fk FOREIGN KEY (nacionalidad_id_nacion) REFERENCES nacionalidad(id_nacion);


-- ====================================================
-- 9. TABLA JUGADOR
-- ====================================================

CREATE TABLE jugador (
    nro_inscripcion           NUMBER(9)    NOT NULL,
    puesto                    VARCHAR2(20) NOT NULL,
    total_premios             NUMBER(10)   NOT NULL,
    anio_fin_amateur          NUMBER(4),
    asociacion_cod_asociacion NUMBER(2)    NOT NULL,
    escuela_futbol_id_escuela NUMBER(4)
);

    ALTER TABLE jugador ADD CONSTRAINT jugador_pk PRIMARY KEY (nro_inscripcion);
    ALTER TABLE jugador ADD CONSTRAINT jugador_trabajador_fk FOREIGN KEY (nro_inscripcion) REFERENCES trabajador(nro_inscripcion);
    ALTER TABLE jugador ADD CONSTRAINT jugador_asociacion_fk FOREIGN KEY (asociacion_cod_asociacion) REFERENCES asociacion(cod_asociacion);
    ALTER TABLE jugador ADD CONSTRAINT jugador_escuela_futbol_fk FOREIGN KEY (escuela_futbol_id_escuela) REFERENCES escuela_futbol(id_escuela);


-- ====================================================
-- 10. TABLA PERSONAL_PLANTA
-- ====================================================

CREATE TABLE personal_planta (
    nro_inscripcion     NUMBER(9) NOT NULL,
    horas_trabajadas    NUMBER(3),
    valor_he            NUMBER(6),
    club_futbol_id_club NUMBER(3) NOT NULL
);

    ALTER TABLE personal_planta ADD CONSTRAINT personal_planta_pk PRIMARY KEY (nro_inscripcion);
    ALTER TABLE personal_planta ADD CONSTRAINT personal_planta_trabajador_fk FOREIGN KEY (nro_inscripcion) REFERENCES trabajador(nro_inscripcion);
    ALTER TABLE personal_planta ADD CONSTRAINT personal_planta_club_futbol_fk FOREIGN KEY (club_futbol_id_club) REFERENCES club_futbol(id_club);


-- ====================================================
-- 11. TABLA JUGADOR_CLUB
-- ====================================================

CREATE TABLE jugador_club (
    fecha_inicio            DATE      NOT NULL,
    fecha_fin               DATE,
    jugador_nro_inscripcion NUMBER(9) NOT NULL,
    club_futbol_id_club     NUMBER(3) NOT NULL
);

    ALTER TABLE jugador_club ADD CONSTRAINT jugador_club_pk PRIMARY KEY (club_futbol_id_club, jugador_nro_inscripcion);
    ALTER TABLE jugador_club ADD CONSTRAINT jugador_club_club_futbol_fk FOREIGN KEY (club_futbol_id_club) REFERENCES club_futbol(id_club);
    ALTER TABLE jugador_club ADD CONSTRAINT jugador_club_jugador_fk FOREIGN KEY (jugador_nro_inscripcion) REFERENCES jugador(nro_inscripcion);


-- ====================================================
-- 12. TABLA JUGADOR_IDIOMA
-- ====================================================

CREATE TABLE jugador_idioma (
    nivel_dominio           VARCHAR2(10) NOT NULL,
    idioma_id_idioma        CHAR(3)      NOT NULL,
    jugador_nro_inscripcion NUMBER(9)    NOT NULL
);

    ALTER TABLE jugador_idioma ADD CONSTRAINT jugador_idioma_pk PRIMARY KEY (idioma_id_idioma, jugador_nro_inscripcion);
    ALTER TABLE jugador_idioma ADD CONSTRAINT jugador_idioma_idioma_fk FOREIGN KEY (idioma_id_idioma) REFERENCES idioma(id_idioma);
    ALTER TABLE jugador_idioma ADD CONSTRAINT jugador_idioma_jugador_fk FOREIGN KEY (jugador_nro_inscripcion) REFERENCES jugador(nro_inscripcion);


