-- INFORME 1

SELECT cod_asociacion AS codigo,
       nombre AS asociacion,
       fecha_creacion AS fecha,
       tipo
FROM asociacion
WHERE tipo = 'P'
AND fecha_creacion > TO_DATE('31-12-2000', 'DD-MM-YYYY')
ORDER BY fecha_creacion DESC;



-- INFORME 2

SELECT id_club AS codigo,
       nombre_club AS club,
       patrimonio AS patrimonio_pesos,
       ROUND(patrimonio / 955, 2) AS patrimonio_dolares,
       tipo_club AS tipo
FROM club_futbol
WHERE LOWER(nombre_club) LIKE '%a%'
AND patrimonio > 200000000
AND tipo_club = 'Profesional'
ORDER BY id_club DESC;
